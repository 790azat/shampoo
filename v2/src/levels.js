export const ROWS = 17;
// expand chunk names into one grid of characters (array of strings)
export function buildMap(level) {
  const rows = Array.from({ length: ROWS }, () => '');
  for (const name of level.chunks) {
    const c = CH[name], w = Math.max(...c.map(r => r.length));
    for (let y = 0; y < ROWS; y++) {
      const r = c[y - (ROWS - c.length)];
      rows[y] += (r || '').padEnd(w, '.');
    }
  }
  return rows;
}
